    if (minutes !== undefined && (minutes < 10 || minutes > 1440)) {
      throw new Error(`auth-kit: schedule "${expression}" must run between every 10 minutes and once a day.`);
    }
    const mode = props.inviteMode ?? 'emailed-code';

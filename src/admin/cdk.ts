/**
 * Who has which role on which item (resource roles, ADR 0022), for `createDynamoResourceStore`:
 * - partition `pk` (`resource#<type>#<id>`), sort `sk` (`meta` or `person#<sub>`), and the
 *   `byPerson` index (`personKey`, `pk`) for "my items" (`RESOURCE_TABLE_SCHEMA`);
 * - on-demand billing, point-in-time recovery (35 days), deletion protection, retained on stack
 *   delete, and a resource policy that denies deleting the table to every principal (outside sandboxes).
 *
 * Grant the app with `grantApp(role)`: `GetItem`, `PutItem`, `DeleteItem` on the table and `Query` on
 * it and its index, nothing else. Every membership change is also written to the audit log by the
 * app (`createResourceActions`), so this table holds the current state and the log holds the history.
 */
export class ResourceAccessTable extends Construct {
  readonly table: dynamodb.TableV2;
  readonly tableName: string;
  readonly tableArn: string;
  private readonly encryptionKey: kms.IKey | undefined;

  constructor(scope: Construct, id: string, props: ResourceAccessTableProps = {}) {
    super(scope, id);
    const sandbox = props.sandbox ?? this.node.tryGetContext(AMPLIFY_DEPLOYMENT_TYPE_CONTEXT_KEY) === 'sandbox';
    this.encryptionKey = props.encryptionKey;
    const { partitionKey, sortKey, indexes } = RESOURCE_TABLE_SCHEMA;
    this.table = new dynamodb.TableV2(this, 'Table', {
      ...(props.tableName !== undefined && { tableName: props.tableName }),
      partitionKey: { name: partitionKey, type: dynamodb.AttributeType.STRING },
      sortKey: { name: sortKey, type: dynamodb.AttributeType.STRING },
      billing: dynamodb.Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: !sandbox,
      removalPolicy: sandbox ? RemovalPolicy.DESTROY : RemovalPolicy.RETAIN,
      ...(props.encryptionKey !== undefined && {
        encryption: dynamodb.TableEncryptionV2.customerManagedKey(props.encryptionKey),
      }),
      globalSecondaryIndexes: [
        {
          indexName: indexes.byPerson.name,
          partitionKey: { name: indexes.byPerson.partitionKey, type: dynamodb.AttributeType.STRING },
          sortKey: { name: indexes.byPerson.sortKey, type: dynamodb.AttributeType.STRING },
          projectionType: dynamodb.ProjectionType.ALL,
        },
      ],
      ...(!sandbox && {
        resourcePolicy: iam.PolicyDocument.fromJson({
          Version: '2012-10-17',
          Statement: [{ Sid: 'ResourceAccessIsKept', Effect: 'Deny', Principal: '*', Action: ['dynamodb:DeleteTable'], Resource: '*' }],
        }),
      }),
    });
    this.tableName = this.table.tableName;
    this.tableArn = this.table.tableArn;
    Tags.of(this).add('ManagedBy', 'auth-kit');
    Tags.of(this).add('Component', 'resource-access');
  }

  /** `GetItem`, `PutItem`, `DeleteItem` on the table and `Query` on it and its index, added to the grantee's own policy. */
  grantApp(grantee: iam.IGrantable): iam.Grant {
    const grant = iam.Grant.addToPrincipal({ grantee, actions: [...RESOURCE_ACCESS_APP_ACTIONS.item], resourceArns: [this.tableArn] });
    grant.combine(
      iam.Grant.addToPrincipal({ grantee, actions: [...RESOURCE_ACCESS_APP_ACTIONS.query], resourceArns: [this.tableArn, `${this.tableArn}/index/*`] }),
    );
    this.encryptionKey?.grantEncryptDecrypt(grantee);
    return grant;
  }
}


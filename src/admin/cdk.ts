export interface AuditLogTableProps {
  /** Default: generated by CloudFormation. */
  tableName?: string;
  /**
   * A throwaway sandbox: no deletion protection, removed with the stack, and no deny on deleting the
   * table. Default: true when Amplify's CDK context says this is a sandbox deployment.
   */
  sandbox?: boolean;
  /** A customer-managed key. Default: DynamoDB's AWS-owned key. */
  encryptionKey?: kms.IKey;
  /**
   * Alert when any row is modified or removed (which the app's code never does): an EventBridge Pipe
   * reads the table's stream, keeps only MODIFY and REMOVE records, and publishes them to this topic.
   */
  tamperAlerts?: { topic: sns.ITopic };
}

/**
 * The append-only audit table:
 * - partition `pk`, sort `sk`, with `byActor` and `byTarget` indexes (`AUDIT_TABLE_SCHEMA`);
 * - on-demand billing, point-in-time recovery (35 days), deletion protection, retained on stack delete;
 * - a stream of old and new images, so any change to a row is visible and recoverable;
 * - a resource policy that denies `UpdateItem`, `DeleteItem`, `BatchWriteItem`, PartiQL updates and
 *   deletes, and `DeleteTable` to every principal, owners and account admins included.
 *
 * Grant the app with `grantAppendAndQuery(role)`: `PutItem` and `Query`, nothing else.
 */
export class AuditLogTable extends Construct {
  readonly table: dynamodb.TableV2;
  readonly tableName: string;
  readonly tableArn: string;
  private readonly encryptionKey: kms.IKey | undefined;

  constructor(scope: Construct, id: string, props: AuditLogTableProps = {}) {
    super(scope, id);
    const sandbox = props.sandbox ?? this.node.tryGetContext(AMPLIFY_DEPLOYMENT_TYPE_CONTEXT_KEY) === 'sandbox';
    this.encryptionKey = props.encryptionKey;
    const { partitionKey, sortKey, indexes } = AUDIT_TABLE_SCHEMA;
    const policyJson = auditLogResourcePolicy({ denyDeleteTable: !sandbox });

    this.table = new dynamodb.TableV2(this, 'Table', {
      ...(props.tableName !== undefined && { tableName: props.tableName }),
      partitionKey: { name: partitionKey, type: dynamodb.AttributeType.STRING },
      sortKey: { name: sortKey, type: dynamodb.AttributeType.STRING },
      billing: dynamodb.Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: !sandbox,
      removalPolicy: sandbox ? RemovalPolicy.DESTROY : RemovalPolicy.RETAIN,
      dynamoStream: dynamodb.StreamViewType.NEW_AND_OLD_IMAGES,
      ...(props.encryptionKey !== undefined && {
        encryption: dynamodb.TableEncryptionV2.customerManagedKey(props.encryptionKey),
      }),
      globalSecondaryIndexes: [indexes.byActor, indexes.byTarget].map((index) => ({
        indexName: index.name,
        partitionKey: { name: index.partitionKey, type: dynamodb.AttributeType.STRING },
        sortKey: { name: sortKey, type: dynamodb.AttributeType.STRING },
        projectionType: dynamodb.ProjectionType.ALL,
      })),
      resourcePolicy: iam.PolicyDocument.fromJson(policyJson),
    });
    this.tableName = this.table.tableName;
    this.tableArn = this.table.tableArn;
    Tags.of(this).add('ManagedBy', 'auth-kit');
    Tags.of(this).add('Component', 'audit-log');

    if (props.tamperAlerts) this.addTamperAlerts(props.tamperAlerts.topic);
  }

  /** `PutItem` on the table only, added to the grantee's own policy: for writers that never read the log. */
  grantAppend(grantee: iam.IGrantable): iam.Grant {
    const grant = iam.Grant.addToPrincipal({ grantee, actions: [...AUDIT_LOG_APP_ACTIONS.append], resourceArns: [this.tableArn] });
    this.encryptionKey?.grantEncryptDecrypt(grantee);
    return grant;
  }

  /** `PutItem` on the table and `Query` on the table and its indexes, added to the grantee's own policy. */
  grantAppendAndQuery(grantee: iam.IGrantable): iam.Grant {
    const grant = iam.Grant.addToPrincipal({ grantee, actions: [...AUDIT_LOG_APP_ACTIONS.append], resourceArns: [this.tableArn] });
    grant.combine(
      iam.Grant.addToPrincipal({ grantee, actions: [...AUDIT_LOG_APP_ACTIONS.read], resourceArns: [this.tableArn, `${this.tableArn}/index/*`] }),
    );
    this.encryptionKey?.grantEncryptDecrypt(grantee);
    return grant;
  }

  private addTamperAlerts(topic: sns.ITopic): void {
    const streamArn = this.table.tableStreamArn;
    if (!streamArn) throw new Error('auth-kit: the audit table has no stream.');
    const role = new iam.Role(this, 'TamperAlertRole', { assumedBy: new iam.ServicePrincipal('pipes.amazonaws.com') });
    role.addToPolicy(
      new iam.PolicyStatement({
        actions: ['dynamodb:DescribeStream', 'dynamodb:GetRecords', 'dynamodb:GetShardIterator', 'dynamodb:ListStreams'],
        resources: [streamArn],
      }),
    );
    topic.grantPublish(role);
    this.encryptionKey?.grantDecrypt(role);
    new pipes.CfnPipe(this, 'TamperAlerts', {
      roleArn: role.roleArn,
      source: streamArn,
      sourceParameters: {
        dynamoDbStreamParameters: { startingPosition: 'LATEST', batchSize: 1 },
        filterCriteria: { filters: [{ pattern: JSON.stringify({ eventName: ['MODIFY', 'REMOVE'] }) }] },
      },
      target: topic.topicArn,
      description: 'auth-kit: an audit row was modified or removed',
    });
  }
}

